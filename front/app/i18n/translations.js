export function translate(locale, key, params = {}) {
  const normalized = normalizeLocale(locale);
  const parts = String(key).split(".");

  const getFromDict = (lang) => {
    let cur = TRANSLATIONS[lang];
    for (const part of parts) {
      if (cur == null || typeof cur !== "object") return undefined;
      cur = cur[part];
    }
    return typeof cur === "string" ? cur : undefined;
  };

  let template = getFromDict(normalized) ?? getFromDict(DEFAULT_LOCALE) ?? String(key);

  if (params && typeof params === "object") {
    for (const [paramKey, paramValue] of Object.entries(params)) {
      template = template.replace(new RegExp(`\\{${paramKey}\\}`, "g"), String(paramValue ?? ""));
    }
  }

  return template;
}

export function translatePhrase(locale, frenchPhrase) {
  if (!frenchPhrase || typeof frenchPhrase !== "string") return frenchPhrase;
  const normalized = normalizeLocale(locale);
  if (normalized === "fr") return frenchPhrase;
  return PHRASE_TRANSLATIONS[normalized]?.[frenchPhrase] || frenchPhrase;
}

